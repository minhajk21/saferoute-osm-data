#!/usr/bin/env python3
"""Write config/known_incomplete.json: the tiles each check may find incomplete.

Usage: python3 -I tools/known_incomplete.py INDEX_V1_JSON [OUT_JSON]

From the extracts' polygons alone (config/sources.json, Geofabrik's
index-v1.json), lists per region the tiles of its box (places) and of its
widened box (lighting) that no downloaded polygon wholly covers, and the same
for the app's UK outline (config/uk_outline.json). These are open water. The
weekly sanity check fails on any OTHER incomplete tile, so a Geofabrik
polygon change or a hole from missing data stops the publish. Rerun after
changing sources.json or regions.json, and review the diff.
"""
import json
import os
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from pipeline import coverage, regions  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def outline_tiles(path):
    with open(path, encoding='utf-8') as f:
        rings = json.load(f)['rings']
    out = set()
    for ring in rings:
        poly = coverage.Polygon(coverage.geometry_edges({'type': 'Polygon', 'coordinates': [ring]}))
        for ry, cols in coverage.touched_tiles(poly).items():
            out.update((tx, ry) for tx in cols)
    return out


def main():
    t0 = time.monotonic()
    index_path = sys.argv[1]
    out_path = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, 'config', 'known_incomplete.json')
    with open(index_path, encoding='utf-8') as f:
        feats = {ft['properties']['id']: ft for ft in json.load(f)['features']}
    srcs = json.load(open(os.path.join(ROOT, 'config', 'sources.json')))['sources']
    cfg = regions.load(os.path.join(ROOT, 'config', 'regions.json'))
    mask = regions.lighting_mask(cfg)
    pp, lp = [], []
    for s in srcs:
        edges = coverage.geometry_edges(feats[s['id']]['geometry'])
        pp.append(coverage.Polygon(edges))
        lp.append(coverage.Polygon(edges, mask=None if s['lighting'] == 'whole' else mask))
    pcov = coverage.complete_tiles(pp)
    lcov = coverage.complete_tiles(lp)

    def holes(tiles_, cov):
        return sorted(f'{tx},{ty}' for tx, ty in tiles_ if tx not in cov.get(ty, ()))

    doc = {'_comment': ('Tiles the sanity check accepts as incomplete (open water outside every downloaded '
                        'extract polygon). Generated by tools/known_incomplete.py from Geofabrik index-v1.json; '
                        'do not edit by hand.'),
           'places_complete_tiles': coverage.count(pcov), 'lighting_complete_tiles': coverage.count(lcov),
           'regions': {}}
    for r in cfg['regions']:
        doc['regions'][r['name']] = {
            'places': holes(regions.region_tiles(r, widened=False), pcov),
            'lighting': holes(regions.region_tiles(r, widened=True), lcov)}
    uk = outline_tiles(os.path.join(ROOT, 'config', 'uk_outline.json'))
    doc['uk_outline'] = {'tiles': len(uk), 'places': holes(uk, pcov), 'lighting': holes(uk, lcov)}
    with open(out_path, 'w', encoding='utf-8') as f:
        f.write(json.dumps(doc, indent=1, sort_keys=True) + '\n')
    summary = {k: (len(v['places']), len(v['lighting'])) for k, v in doc['regions'].items()}
    summary['uk_outline'] = (len(doc['uk_outline']['places']), len(doc['uk_outline']['lighting']), len(uk))
    print(json.dumps({'places_complete': doc['places_complete_tiles'], 'lighting_complete': doc['lighting_complete_tiles'],
                      'holes (places, lighting)': summary, 'seconds': round(time.monotonic() - t0, 1)}, indent=1))


if __name__ == '__main__':
    main()
